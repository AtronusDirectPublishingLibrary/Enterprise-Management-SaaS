export const SOCIAL_PLATFORMS = ["facebook", "x", "linkedin", "telegram", "youtube"];

export const SOCIAL_LABELS = {
  facebook: "Facebook",
  x: "X (Twitter)",
  linkedin: "LinkedIn",
  telegram: "Telegram",
  youtube: "YouTube",
};

export function SocialIcon({ platform, size = 16 }) {
  const path = PATHS[platform];
  if (!path) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      <path d={path} />
    </svg>
  );
}

export default function SocialLinks({ links = [], className = "" }) {
  const visible = (links || []).filter((link) => link && link.enabled !== false && (link.url || "").trim());
  if (!visible.length) return null;

  return (
    <ul className={`social-links${className ? ` ${className}` : ""}`}>
      {visible.map((link) => (
        <li key={link.platform}>
          <a
            href={link.url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={SOCIAL_LABELS[link.platform] || link.platform}
            title={SOCIAL_LABELS[link.platform] || link.platform}
          >
            <SocialIcon platform={link.platform} />
          </a>
        </li>
      ))}
    </ul>
  );
}
